// Regenerates files derived from the style spec and from the source's JSDoc:
//   src/operator-names.ts             every expression operator
//   src/style-properties.ts           every layer paint/layout property name
//   test/jsdoc-examples.generated.ts  every JSDoc @example, as code that tsc and a test check
//
// `node scripts/generate.mjs` writes them; `--check` fails if any is out of date.
import { execFileSync } from "node:child_process"
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { join, relative, resolve } from "node:path"
import process from "node:process"

const root = resolve(import.meta.dirname, "..")
const check = process.argv.includes("--check")
const spec = createRequire(import.meta.url)("@maplibre/maplibre-gl-style-spec/dist/latest.json")

const operators = Object.keys(spec.expression_name.values)
const properties = [...new Set(Object.keys(spec).filter(key => /^(?:paint|layout)_/.test(key)).flatMap(key => Object.keys(spec[key])))].sort()

const files = {
  "src/operator-names.ts": `/**
 * Every expression operator in the MapLibre style spec. Generated by
 * \`scripts/generate.mjs\`; kept in sync by \`test/coverage.test.ts\`.
 */
const NAMES = [
${operators.map(name => `  ${JSON.stringify(name)},`).join("\n")}
] as const

/** The name of a MapLibre expression operator, like \`"get"\` or \`"+"\`. */
export type OperatorName = (typeof NAMES)[number]

/** @internal */
export const OPERATOR_NAMES: ReadonlySet<string> = /* @__PURE__ */ new Set(NAMES)

/** \`true\` if \`value\` is an expression array (its head is a spec operator). @internal */
export function isExpression(value: unknown): value is readonly [OperatorName, ...unknown[]] {
  return Array.isArray(value) && typeof value[0] === "string" && OPERATOR_NAMES.has(value[0])
}
`,
  "src/style-properties.ts": `/**
 * Every layer paint and layout property in the MapLibre style spec.
 * Generated by \`scripts/generate.mjs\`; kept in sync by \`test/coverage.test.ts\`.
 */
export type StylePropertyName =
${properties.map(name => `  | ${JSON.stringify(name)}`).join("\n")}
`,
  "test/jsdoc-examples.generated.ts": examplesFile(),
}

// The two source files are linted after writing, so compare them by content
// that lint doesn't change: the quoted names.
const names = text => [...text.matchAll(/"([^"]+)"/g)].map(m => m[1]).join("\n")
const stale = Object.entries(files).filter(([file, content]) => {
  const current = readFileSync(join(root, file), "utf8")
  return file.endsWith(".generated.ts") ? current !== content : names(current) !== names(content)
}).map(([file]) => file)

if (check) {
  if (stale.length) {
    console.error(`Out of date: ${stale.join(", ")}. Run \`pnpm generate\`.`)
    process.exitCode = 1
  }
}
else {
  for (const [file, content] of Object.entries(files))
    writeFileSync(join(root, file), content)
  execFileSync("pnpm", ["exec", "eslint", "--fix", "src/operator-names.ts", "src/style-properties.ts"], { cwd: root, stdio: "inherit" })
  console.log(`generated ${Object.keys(files).join(", ")}`)
}

/** Every `@example` in src/, one entry per top-level statement. */
function examplesFile() {
  const sources = readdirSync(join(root, "src"), { recursive: true }).filter(f => f.endsWith(".ts")).sort()
  const entries = []
  for (const file of sources) {
    const text = readFileSync(join(root, "src", file), "utf8")
    for (const [, block] of text.matchAll(/\/\*\*((?:(?!\*\/)[\s\S])*)\*\//g)) {
      const lines = block.split("\n").map(line => line.replace(/^\s*\* ?/, ""))
      for (let i = 0; i < lines.length; i++) {
        if (!lines[i].startsWith("@example"))
          continue
        const body = [lines[i].slice("@example".length).trim()]
        while (i + 1 < lines.length && !lines[i + 1].startsWith("@"))
          body.push(lines[++i])
        const code = body.filter(line => !line.trim().startsWith("//")).map(line => line.replace(/\s+\/\/.*$/, "")).join("\n").trim()
        // Examples that wire up a map, declare types or bind variables are covered by the README tests.
        if (!code || /\bmap\b|setInterval|useEffect|\binterface\b|\bconst\b|\blet\b|\bimport\b/.test(code))
          continue
        statements(code).forEach((statement, n) => {
          entries.push([`${relative(join(root, "src"), join(root, "src", file))}:${entries.length}${n ? `.${n}` : ""}`, statement.replace(/^(?:"[^"]+"|[a-z]\w*)\s*:\s*/i, "")])
        })
      }
    }
  }
  const exportsOf = file => [...readFileSync(join(root, "src", file), "utf8").matchAll(/^export function (\w+)/gm)].map(m => m[1])
  // The /testing entry is testing.ts plus what it re-exports from lint.ts
  const reexported = [...readFileSync(join(root, "src/testing.ts"), "utf8").matchAll(/^export \{([^}]*)\} from "\.\/lint"/gm)]
    .flatMap(m => m[1].split(",").map(name => name.trim()).filter(name => name && !name.startsWith("type ")))
  const testing = [...new Set([...exportsOf("testing.ts"), ...reexported])].sort()
  const exported = new Set(sources.filter(file => !["testing.ts", "lint.ts", "internal.ts", "operator-names.ts"].includes(file)).flatMap(exportsOf))
  return `// Generated by scripts/generate.mjs from the JSDoc @example blocks in src/. Do not edit.
/* eslint-disable */
import {
${[...exported].sort().map(name => `  ${name},`).join("\n")}
} from "../src"
import { ${testing.join(", ")} } from "../src/testing"

export const examples: [where: string, build: () => unknown][] = [
${entries.map(([where, code]) => `  [${JSON.stringify(where)}, () => (${code})],`).join("\n")}
]
`
}

/** Splits code into top-level statements where brackets balance. */
function statements(code) {
  const out = []
  let current = []
  let depth = 0
  for (const line of code.split("\n")) {
    current.push(line)
    for (const ch of line) {
      if ("([{".includes(ch))
        depth++
      else if (")]}".includes(ch))
        depth--
    }
    if (depth === 0) {
      out.push(current.join("\n").trim())
      current = []
    }
  }
  if (current.length)
    out.push(current.join("\n").trim())
  return out.filter(Boolean)
}
